        public static bool Tr;

        public static void Load() { Tr = Settings.Get("Language", "en") == "tr"; }

        public static void Set(bool turkish)
        {
            Tr = turkish;
            Settings.Set("Language", turkish ? "tr" : "en");
            Settings.Save();
        }

        public static string T(string en)
        {
            if (!Tr || en == null) return en;
            string v;
            if (Map.TryGetValue(en, out v)) return v;
            return en;
        }

        public static string T(string en, params object[] args)
        {
            return string.Format(T(en), args);
        }

        static Dictionary<string, string> _map;
        static Dictionary<string, string> Map
        {
            get
            {
                if (_map == null)
                {
                    _map = new Dictionary<string, string>(StringComparer.Ordinal);
                    for (int i = 0; i + 1 < Pairs.Length; i += 2) _map[Pairs[i]] = Pairs[i + 1];
                }
                return _map;
            }
        }

        public static int Count { get { return Map.Count; } }

